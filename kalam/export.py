# ---------------------------------------------------------------- .klm
def save_klm(session, path, view=None, lang='fr'):
    data = {
        'format': 'kalam', 'version': 2, 'lang': lang, 'view2d': view or {},
        'cells': session.cells_json(),
        'commands': [c.to_json() for c in session.registry.user_commands()],
    }
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)


def load_klm(path, registry):
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    if data.get('format') != 'kalam':
        raise ValueError('not a Kalam file')
    for d in data.get('commands', []):
        if d['name'] not in registry.commands:
            registry.add_user(d)
    s = Session(registry)
    s.load_cells(data['cells'])
    return s, data.get('view2d') or {}, data.get('lang')


# ---------------------------------------------------------------- python
def _names(code):
    out, prev = [], None
    for tok in tokenize.generate_tokens(io.StringIO(code).readline):
        if tok.type == tokenize.NAME and prev != '.' and not keyword.iskeyword(tok.string):
            out.append(tok.string)
        prev = tok.string
    return out


def to_python(session):
    reg = session.registry
    src = inspect.getsource(runtime)
    lines = [
        '# Generated by Kalam - needs only SymPy:  pip install sympy',
        '# ---------------------------------------------------------------- Kalam runtime',
        src.rstrip(),
        '',
        'from sympy import (%s)' % ', '.join(n for n in GLOBALS_BASE if n not in ('sp', 'e_', 'i_')),
        'e_, i_ = sp.E, sp.I',
    ]
    for c in reg.user_commands():
        lines += ['', '# user command %s' % c.name, c.code.rstrip(), '%s = run' % c.name]
    lines += ['', '# ---------------------------------------------------------------- notebook']
    known = set(GLOBALS_BASE) | set(reg.commands) | set(vars(runtime)) | {'e_', 'i_'}
    declared = {'x', 'y', 'z', 't'}
    cell_number = {b: k for k, b in enumerate(session.blocks(), 1)}    # $n = cell n on screen
    for c in session.cells:
        n = cell_number[c.block]
        if c.is_text:
            lines += ['', '# ' + c.text.replace('\n', '\n# ')]
            continue
        if c.norm is None:
            continue
        lines.append('')
        if c.error:
            lines.append('# cell %d (error in Kalam: %s): %s' % (n, c.error, c.text))
            continue
        local = set(c.params or [])
        new = [v for v in _names(c.norm) if v not in known | declared | local and v != c.name]
        new = list(dict.fromkeys(new))
        if new:
            lines.append("%s, = sp.symbols('%s', seq=True)" % (', '.join(new), ' '.join(new)))
            declared |= set(new)
        if c.slider:
            expr = fmt(c.value)
            lines.append('# slider [%s, %s]' % (fmt(c.slider.lo), fmt(c.slider.hi)))
            expr = 'sp.nsimplify(%s)' % expr
        elif c.params:
            ps = ', '.join(c.params)
            pre = "%s, = sp.symbols('%s', seq=True)\n" % (ps, ' '.join(c.params)) \
                if local - declared else ''
            if pre:
                lines.append(pre.rstrip())
                declared |= local
            expr = 'Lambda((%s), %s)' % (ps + (',' if len(c.params) == 1 else ''), c.norm)
        elif isinstance(c.value, sp.Point) and c.norm.startswith('('):
            expr = 'Point' + c.norm            # Kalam turns (1, 2) into a point
        else:
            expr = c.norm
        target = c.name or '_c%d' % n
        lines.append('%s = %s%s' % (target, expr, '  # ' + c.note if c.note else ''))
        if c.name:
            lines.append('_c%d = %s' % (n, c.name))
            known.add(c.name)
        known.add('_c%d' % n)
        lines.append("print(%r, %s)" % ('[%d] %s' % (n, (c.name + ' =') if c.name else ''), target))
    return '\n'.join(lines) + '\n'


# ---------------------------------------------------------------- latex notebook
_PREAMBLE = {
    'fr': '\\usepackage[T1]{fontenc}\n\\usepackage[french]{babel}\n',
    'en': '\\usepackage[T1]{fontenc}\n',
    'ar': '% compile with XeLaTeX or LuaLaTeX\n\\usepackage{polyglossia}\n'
          '\\setmainlanguage{arabic}\\setotherlanguage{english}\n'
          '\\newfontfamily\\arabicfont[Script=Arabic]{Amiri}\n',
}


_ESC = {'\\': r'\textbackslash{}', '{': r'\{', '}': r'\}', '$': r'\$', '&': r'\&', '#': r'\#',
        '^': r'\^{}', '_': r'\_', '%': r'\%', '~': r'\~{}'}


_MATHCH = {'π': r'\pi', '√': r'\surd', '²': '^2', '³': '^3', '∞': r'\infty', '≤': r'\le', '≥': r'\ge',
           '≠': r'\neq', '×': r'\times', '÷': r'\div', '·': r'\cdot', 'α': r'\alpha', 'β': r'\beta', 'θ': r'\theta'}


def _escape(s):
    return ''.join(_ESC.get(ch) or ('$%s$' % _MATHCH[ch] if ch in _MATHCH else ch) for ch in s)


def _tex_text(s):
    """Text cell to LaTeX: keep $...$ math, escape the rest."""
    out = []
    for i, part in enumerate(re.split(r'(\$[^$]*\$)', s)):
        if i % 2:
            out.append(part)
        else:
            out.append(_escape(part))
    return ''.join(out)


def to_latex(session, lang='fr'):
    """The notebook as shown on screen: text lines are paragraphs, results are formulas; code is not printed."""
    body = []
    for c in session.cells:
        if c.is_text:
            txt = ''.join('$%s$' % s if is_math else s for is_math, s in c.parts)
            body.append(_tex_text(txt) + '\n')
        elif c.error:
            body.append('\\[\\text{\\textcolor{red}{%s}}\\]' % _tex_text(c.error))
        elif c.latex:
            body.append('\\[%s\\]' % c.latex)
    return ('\\documentclass[11pt]{article}\n\\usepackage{amsmath,amssymb,xcolor}\n'
            '\\usepackage[margin=2cm]{geometry}\n' + _PREAMBLE.get(lang, '') +
            '\\begin{document}\n\n' + '\n'.join(body) + '\n\\end{document}\n')


# ---------------------------------------------------------------- tkz figure
class _GnuplotPrinter(StrPrinter):
    """Expression in gnuplot syntax for tkz-fct (variable \\x, 2 decimals)."""

    def __init__(self, var):
        super().__init__()
        self.var = var

    def _print_Symbol(self, e):
        return '\\x' if e == self.var else e.name

    def _print_Rational(self, e):
        return fmt(e)

    def _print_Float(self, e):
        return fmt(e)

    def _print_Abs(self, e):
        return 'abs(%s)' % self._print(e.args[0])

    def _print_Exp1(self, e):
        return 'exp(1)'

    def _print_Pow(self, e, rational=False):
        if e.exp == sp.Rational(1, 2):
            return 'sqrt(%s)' % self._print(e.base)
        return '(%s)**(%s)' % (self._print(e.base), self._print(e.exp))


def _gp(expr, var):
    return _GnuplotPrinter(var).doprint(expr)


def figure_tkz(session, view):
    """2D figure: tkz-euclide for geometry, tkz-fct for functions (standalone, 2 decimals)."""
    xmin, xmax, ymin, ymax = (round(view[k]) for k in ('xmin', 'xmax', 'ymin', 'ymax'))
    defs, draws, fcts, pts, labels, skipped = [], [], [], [], [], []
    aux = [0]
    known = {}      # (x, y) -> point name, so lines reuse A, B instead of new points

    def P(p, name=None):
        key = (fmt(p.x), fmt(p.y))
        if name is None and key in known:
            return known[key]
        if name is None:
            aux[0] += 1
            name = 'k%d' % aux[0]
        known.setdefault(key, name)
        defs.append('\\tkzDefPoint(%s,%s){%s}' % (fmt(p.x), fmt(p.y), name))
        return name

    def explicit(expr, var, a=None, b=None, label=None):
        dom = '%s:%s' % (fmt(xmin if a is None else a), fmt(xmax if b is None else b))
        fcts.append('\\tkzFct[domain=%s,thick]{%s}' % (dom, _gp(expr, var)))

    def draw(v, name):
        if isinstance(v, (list, tuple)):
            for i in v:
                draw(i, None)
        elif isinstance(v, sp.Point2D):
            n = P(v, name if name and name.isascii() else None)
            pts.append(n)
            if name:
                labels.append(n)
        elif isinstance(v, sp.Segment2D):
            draws.append('\\tkzDrawSegment(%s,%s)' % (P(v.p1), P(v.p2)))
        elif isinstance(v, sp.Ray2D):
            draws.append('\\tkzDrawLine[add=0 and 20](%s,%s)' % (P(v.p1), P(v.p2)))
        elif isinstance(v, sp.Line2D):
            draws.append('\\tkzDrawLine[add=20 and 20](%s,%s)' % (P(v.p1), P(v.p2)))
        elif isinstance(v, sp.Circle):
            o = P(v.center)
            r = P(v.center + sp.Point(v.radius, 0))
            draws.append('\\tkzDrawCircle(%s,%s)' % (o, r))
        elif isinstance(v, sp.Polygon):
            draws.append('\\tkzDrawPolygon(%s)' % ','.join(P(p) for p in v.vertices))
        elif isinstance(v, sp.Lambda) and len(v.variables) == 1:
            explicit(v.expr, v.variables[0])
        elif isinstance(v, runtime.Graph):
            explicit(v.expr, v.var, v.a, v.b)
        elif isinstance(v, sp.Equality) and v.lhs == runtime.y and not v.rhs.has(runtime.y):
            explicit(v.rhs, runtime.x)
        elif isinstance(v, runtime.Curve) and v.dim == 2:
            fcts.append('\\tkzFctPar[domain=%s:%s,thick]{%s}{%s}' % (
                fmt(v.a), fmt(v.b), _gp(v.comps[0], v.var).replace('\\x', 't'),
                _gp(v.comps[1], v.var).replace('\\x', 't')))
        else:
            skipped.append(name or type(v).__name__)

    for c in session.cells:
        if c.visible and c.dim == 2:
            draw(c.value, c.name)
    out = ['% Generated by Kalam. tkz-fct needs gnuplot: compile with  pdflatex --shell-escape',
           '\\documentclass[tikz,border=3mm]{standalone}',
           '\\usepackage{tkz-fct}', '\\usepackage{tkz-euclide}',
           '\\begin{document}', '\\begin{tikzpicture}',
           '\\tkzInit[xmin=%d,xmax=%d,ymin=%d,ymax=%d]' % (xmin, xmax, ymin, ymax),
           '\\tkzGrid[color=gray!25]', '\\tkzAxeXY', '\\tkzClip[space=.5]']
    out += defs + draws + fcts
    if pts:
        out.append('\\tkzDrawPoints(%s)' % ','.join(pts))
    if labels:
        out.append('\\tkzLabelPoints[above right](%s)' % ','.join(labels))
    if skipped:
        out.append('% not exported (implicit curves, regions...): ' + ', '.join(skipped))
    out += ['\\end{tikzpicture}', '\\end{document}']
    return '\n'.join(out) + '\n'
